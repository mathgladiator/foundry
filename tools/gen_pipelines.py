GROUNDS = ["soil", "water", "rock", "sand", "path"]


class PlotterGen:
    """A plotter compiled into the native runtime: the same config the foundry's plotter loader
    makes (src/host/plot/plotter.cpp), and a spawn function per kind."""

    def __init__(self, workspace, path, channels, pipelines):
        with open(path) as f:
            self.j = json.load(f)
        self.name = self.j["name"]
        self.src = f"plotters/{os.path.basename(path)}"
        self.channels = channels
        self.pipes = {p.name: p for p in pipelines}
        self.system = self.j["system"]
        self.distinct = max(1, int(self.j.get("distinct_seeds", 6)))
        cfg = self.j.get("config", {})
        layers = cfg["layers"]
        names = [L["name"] for L in layers]
        self.kinds = []
        out_layers = []
        for L in layers:
            def mask(lst):
                m = 0
                for g in lst or []:
                    if g not in GROUNDS:
                        sys.exit(f"{self.src}: unknown ground {g}")
                    m |= 1 << GROUNDS.index(g)
                return m
            grove = L.get("grove", [1.0, 1.0])
            edge = L.get("edge", {})
            lo = {"name": L["name"], "spacing_m": L["spacing_m"], "density": L["density"],
                  "grove_low": grove[0], "grove_high": grove[1],
                  "edge_low": edge.get("low", 1.0), "edge_cells": edge.get("cells", 0),
                  "ground": mask(L.get("ground")), "max_height_delta_m": L.get("max_height_delta_m", 0.5),
                  # The foundry's JSON objects iterate in key order: so do these.
                  "keep_clear": [{"layer": names.index(k), "metres": v} for k, v in sorted(L.get("keep_clear", {}).items())],
                  "prefer_near": [{"layer": names.index(k), "within_m": v.get("within_m", 3.0), "boost": v.get("boost", 2.0)}
                                  for k, v in sorted(L.get("prefer_near", {}).items())],
                  "regrows": L.get("regrows", True)}
            for lst in ("kinds", "regrow_kinds"):
                ks = []
                for k in L.get(lst, []):
                    if "footprint_m" not in k:
                        sys.exit(f"{self.src}: kind {k.get('pipeline')} {k.get('params')} has no measured footprint; "
                                 "load the plotter in the foundry (plotter_get) to measure it")
                    kid = len(self.kinds)
                    pipe = self.pipes.get(k["pipeline"])
                    if not pipe:
                        sys.exit(f"{self.src}: no pipeline {k['pipeline']}")
                    label = k["pipeline"] + "".join(" " + v for _, v in sorted(k.get("params", {}).items()) if isinstance(v, str))
                    self.kinds.append({"id": kid, "pipe": pipe, "params": k.get("params", {}), "vary": k.get("vary", {}),
                                       "on_regrow": k.get("on_regrow", {}), "label": label})
                    ks.append({"id": kid, "weight": k.get("weight", 1.0), "footprint_m": k["footprint_m"],
                               "footprint_cells": k.get("footprint_cells", 0), "max_share": k.get("max_share", 1.0),
                               "ground": mask(k.get("ground"))})
                lo[lst] = ks
            out_layers.append(lo)
        self.config = {"grove_scale_cells": cfg.get("grove_scale_cells", 8.0), "grove_octaves": cfg.get("grove_octaves", 2),
                       "layers": out_layers}
        # Fields (design/plotter.md, "Fields"): pipelines that cover the region's cells, one instance each.
        self.fields = []
        for fdef in self.j.get("fields", []):
            pipe = self.pipes.get(fdef["pipeline"])
            if not pipe:
                sys.exit(f"{self.src}: no pipeline {fdef['pipeline']}")
            if not pipe.field:
                sys.exit(f"{self.src}: {pipe.name} is not a field (its draw has no field)")
            label = fdef["pipeline"] + "".join(" " + v for _, v in sorted(fdef.get("params", {}).items()) if isinstance(v, str))
            self.fields.append({"pipe": pipe, "params": fdef.get("params", {}), "label": label})
        # A boundary (design/boundary.md): a terrain pipeline spawned around the region with its hull.
        self.boundary = None
        bdef = self.j.get("boundary")
        if bdef:
            pipe = self.pipes.get(bdef["pipeline"])
            if not pipe:
                sys.exit(f"{self.src}: no pipeline {bdef['pipeline']}")
            if not pipe.hull:
                sys.exit(f"{self.src}: {pipe.name} takes no hull (its draw.terrain names none)")
            label = bdef["pipeline"] + "".join(" " + v for _, v in sorted(bdef.get("params", {}).items()) if isinstance(v, str))
            self.boundary = {"pipe": pipe, "params": bdef.get("params", {}), "label": label}
        self.C = upper(self.name)

    # The pipeline generator's channel-value writers, shared.
    value_cpp = Pipeline.value_cpp
    scalar_cpp = Pipeline.scalar_cpp
    enum_index = Pipeline.enum_index

    def assign(self, pipe, name, value):
        p = next((q for q in pipe.params if q["name"] == name), None)
        if p is None:
            sys.exit(f"{self.src}: {pipe.name} has no parameter {name}")
        if p["type"] in ("enum", "config"):
            return f"p.{name} = {pipe.U}_{upper(name)}_{upper(value)};"
        if p["type"] == "bool":
            return f"p.{name} = {'true' if value else 'false'};"
        if p["type"] == "u32":
            return f"p.{name} = {int(value)}u;"
        return f"p.{name} = {f32(value)};"

    def source(self, index_of):
        o = []
        o.append(f"// {self.name}: compiled from {self.src}.\n")
        o.append(f"namespace {self.system} {{\nbool run(const channels::plot_request &in, channels::plot_result &out, std::string &error);\n}}\n\n")
        o.append("namespace {\n\n")
        o.append(f"const channels::plot_config &config_{self.name}() {{\n  static const channels::plot_config c = [] {{\n"
                 "    channels::plot_config g;\n")
        body = []
        self.value_cpp("plot_config", self.config, "g", body, "    ")
        o.extend(body)
        o.append("    return g;\n  }();\n  return c;\n}\n\n")
        for k in self.kinds:
            pipe = k["pipe"]
            o.append(f"foundry_instance spawn_{self.name}_{k['id']}(foundry_runtime *rt, uint32_t seed, bool regrown, const float t[16]) {{\n")
            o.append(f"  {pipe.C}_params p;\n  {pipe.C}_default_params(&p);\n")
            for name, v in sorted(k["params"].items()):
                o.append("  " + self.assign(pipe, name, v) + "\n")
            o.append("  uint32_t h = plot_hash(seed ^ 0x51ed270bu);\n  (void)h;\n")
            for name, choices in sorted(k["vary"].items()):
                items = sorted(choices.items())
                o.append("  {\n    float total = 0.0f;\n")
                for _, w in items:
                    o.append(f"    total += {f32(w)};\n")
                o.append("    h = plot_hash(h + 0x9e3779b9u);\n"
                         "    float pick = static_cast<float>(h >> 8) / 16777216.0f * total;\n")
                for i, (val, w) in enumerate(items):
                    last = i == len(items) - 1
                    o.append(f"    {'' if i == 0 else 'else '}if ({'true' if last else f'pick < {f32(w)}'}) {self.assign(pipe, name, val)}\n")
                    if not last:
                        o.append(f"    else if ((pick -= {f32(w)}), false) {{}}\n")
                o.append("  }\n")
            if k["on_regrow"]:
                o.append("  if (regrown) {\n")
                for name, v in sorted(k["on_regrow"].items()):
                    o.append("    " + self.assign(pipe, name, v) + "\n")
                o.append("  }\n")
            else:
                o.append("  (void)regrown;\n")
            if any(q["name"] == "seed" for q in pipe.params):
                o.append(f"  p.seed = 1u + (seed % {self.distinct}u);\n")
            o.append(f"  return {pipe.C}_spawn(rt, &p, t);\n}}\n\n")
        for i, fl in enumerate(self.fields):
            pipe = fl["pipe"]
            o.append(f"foundry_instance field_{self.name}_{i}(foundry_runtime *rt, uint32_t world_seed, const float t[16],\n"
                     f"                                    const foundry_field_cell *cells, uint32_t count) {{\n")
            o.append(f"  {pipe.C}_params p;\n  {pipe.C}_default_params(&p);\n")
            for name, v in sorted(fl["params"].items()):
                o.append("  " + self.assign(pipe, name, v) + "\n")
            o.append(f"  p.{pipe.field['seed']} = world_seed;\n")
            o.append(f"  return {pipe.C}_spawn_field(rt, &p, t, cells, count);\n}}\n\n")
        o.append(f"const plotters::Field fields_{self.name}[] = {{\n")
        for i, fl in enumerate(self.fields):
            o.append(f"    {{{c_string(fl['label'])}, field_{self.name}_{i}}},\n")
        if not self.fields:
            o.append("    {nullptr, nullptr},\n")
        o.append("};\n\n")
        if self.boundary:
            pipe = self.boundary["pipe"]
            o.append(f"foundry_instance boundary_{self.name}(foundry_runtime *rt, uint32_t world_seed, const float t[16],\n"
                     f"                                    const foundry_hull_cell *cells, uint32_t count) {{\n")
            o.append(f"  {pipe.C}_params p;\n  {pipe.C}_default_params(&p);\n")
            for name, v in sorted(self.boundary["params"].items()):
                o.append("  " + self.assign(pipe, name, v) + "\n")
            if any(q["name"] == "seed" for q in pipe.params):
                o.append("  p.seed = 1u + (world_seed % 1000000u);\n")
            else:
                o.append("  (void)world_seed;\n")
            o.append(f"  return {pipe.C}_spawn_hull(rt, &p, t, cells, count);\n}}\n\n")
            # Its figures, each spawned from its kind's pipeline (draw.figures.kinds): the species by
            # name, the age, and a seed; the finest detail is the runtime's to choose.
            fig = pipe.draw.get("figures")
            o.append(f"foundry_instance figure_{self.name}(foundry_runtime *rt, const foundry_figure *f, const float t[16]) {{\n")
            if fig:
                for kind_i, kind in enumerate(("tree", "bush")):
                    spec = fig.get("kinds", {}).get(kind)
                    if not spec:
                        continue
                    kp = self.pipes.get(spec["pipeline"])
                    if not kp:
                        sys.exit(f"{self.src}: no pipeline {spec['pipeline']} for {pipe.name}'s figures")
                    sp, ag, sd = spec.get("species", "species"), spec.get("age", "age"), spec.get("seed", "seed")
                    age_n = len(next(q for q in kp.params if q["name"] == ag)["values"])
                    o.append(f"  if (f->kind == {kind_i}u) {{\n    {kp.C}_params p;\n    {kp.C}_default_params(&p);\n")
                    for name, v in sorted(spec.get("params", {}).items()):
                        if name != "detail":
                            o.append("    " + self.assign(kp, name, v) + "\n")
                    o.append(f"    const int s = {kp.C}_{sp}_find(f->species);\n    if (s < 0) return FOUNDRY_NO_INSTANCE;\n"
                             f"    p.{sp} = static_cast<{kp.ctype(next(q for q in kp.params if q['name'] == sp))}>(s);\n"
                             f"    p.{ag} = static_cast<{kp.ctype(next(q for q in kp.params if q['name'] == ag))}>(f->age < {age_n}u ? f->age : {age_n - 1}u);\n"
                             f"    p.{sd} = 1u + (f->seed % {int(spec.get('distinct_seeds', 4))}u);\n"
                             f"    return {kp.C}_spawn(rt, &p, t);\n  }}\n")
            o.append("  (void)rt;\n  (void)f;\n  (void)t;\n  return FOUNDRY_NO_INSTANCE;\n}\n\n")
            o.append(f"const plotters::Boundary boundary_info_{self.name} = {{{c_string(self.boundary['label'])}, boundary_{self.name}, figure_{self.name}}};\n\n")
        o.append(f"const plotters::Kind kinds_{self.name}[] = {{\n")
        for k in self.kinds:
            o.append(f"    {{{c_string(k['label'])}, spawn_{self.name}_{k['id']}}},\n")
        o.append("};\n\n}  // namespace\n\n")
        return "".join(o)


def plotters_files(plotters):
    h = [banner("the workspace's plotters/", True),
         "/* The approved plotters (design/plotter.md): pass one in foundry_region_desc. */\n"]
    for i, p in enumerate(plotters):
        h.append(f"#define FOUNDRY_PLOTTER_{p.C} ((foundry_plotter){i})\n")
    h.append(f"#define FOUNDRY_PLOTTER_COUNT {len(plotters)}u\n")
    c = [banner("the workspace's plotters/"),
         "// The compiled plotters: each one's config, its plot system called natively, and its kinds.\n"
         "#include <string>\n\n#include \"plotters_internal.h\"\n\n"]
    used = []
    for p in plotters:
        if "plot_config" not in used:
            used.append("plot_config")
    c.append("#include \"channels/plot_config.h\"\n\n")
    c.append("namespace {\n\nuint32_t plot_hash(uint32_t x) {\n  x ^= x >> 16;\n  x *= 0x7feb352du;\n  x ^= x >> 15;\n"
             "  x *= 0x846ca68bu;\n  x ^= x >> 16;\n  return x;\n}\n\n}  // namespace\n\n")
    for i, p in enumerate(plotters):
        c.append(p.source(i))
    c.append("namespace plotters {\n\nnamespace {\nconst Info kInfos[] = {\n")
    for p in plotters:
        c.append(f"    {{{c_string(p.name)}, config_{p.name}, {p.system}::run, kinds_{p.name}, {len(p.kinds)}u, fields_{p.name}, "
                 f"{len(p.fields)}u, {'&boundary_info_' + p.name if p.boundary else 'nullptr'}}},\n")
    if not plotters:
        c.append("    {nullptr, nullptr, nullptr, nullptr, 0u, nullptr, 0u, nullptr},\n")
    c.append("};\n}  // namespace\n\n")
    c.append(f"uint32_t count() {{ return {len(plotters)}u; }}\n\n"
             "const Info *info(foundry_plotter plotter) { return plotter < count() ? &kInfos[plotter] : nullptr; }\n\n"
             "}  // namespace plotters\n")
    return "".join(h), "".join(c)


def fires_files(workspace):
    """The fire configs (config/fire_configs/), compiled in for the runtime's fire system."""
    tdir = os.path.join(workspace, "config", "fire_configs")
    entries = []
    if os.path.isdir(tdir):
        for fn in sorted(os.listdir(tdir)):
            if fn.endswith(".json") and fn != "table.json":
                with open(os.path.join(tdir, fn)) as f:
                    entries.append(json.load(f)["value"])
    entries.sort(key=lambda v: v["id"])
    ids = [v["id"] for v in entries]
    if len(set(ids)) != len(ids):
        sys.exit("config/fire_configs: two fires share an id")
    kinds = {"flame": 0, "ember": 1, "spirit": 2}
    h = (banner("config/fire_configs") + "// The fire configs compiled in (design/submit.md, \"Fire\").\n#pragma once\n\n#include <vector>\n\n"
         "#include \"fire/fire.h\"\n\nnamespace fires {\nconst std::vector<runtime::fire::Config> &configs();\nconst char *const *names();\n}  // namespace fires\n")
    c = [banner("config/fire_configs"), "#include \"fires.h\"\n\nnamespace fires {\n\nconst std::vector<runtime::fire::Config> &configs() {\n",
         "  static const std::vector<runtime::fire::Config> c = [] {\n    std::vector<runtime::fire::Config> v;\n"]
    def v3(x):
        return ", ".join(f32(a) for a in x)
    for v in entries:
        k = v["kind"] if isinstance(v["kind"], int) else kinds[v["kind"]]
        c.append(f"    {{  // {v['name']}\n      runtime::fire::Config f;\n      f.id = {v['id']}u;\n      f.kind = {k}u;\n")
        for a in ("core", "tip"):
            c.append(f"      {{ const float x[3] = {{{v3(v[a + '_color'])}}}; for (int i = 0; i < 3; ++i) f.{a}[i] = x[i]; }}\n")
        c.append(f"      {{ const float x[3] = {{{v3(v['smoke_color'])}}}; for (int i = 0; i < 3; ++i) f.smoke[i] = x[i]; }}\n")
        c.append(f"      {{ const float x[3] = {{{v3(v['light_color'])}}}; for (int i = 0; i < 3; ++i) f.light[i] = x[i]; }}\n")
        for a in ("size", "height", "rate", "flicker", "sparks", "smoke_rate", "smoke_size", "smoke_life", "smoke_rise", "light_radius", "light_strength"):
            c.append(f"      f.{a} = {f32(v[a])};\n")
        c.append("      v.push_back(f);\n    }\n")
    c.append("    return v;\n  }();\n  return c;\n}\n\nconst char *const *names() {\n  static const char *const n[] = {")
    c.append(", ".join(c_string(v["name"]) for v in entries) + (", " if entries else "") + "nullptr};\n  return n;\n}\n\n}  // namespace fires\n")
    return h, "".join(c)


def main():
    check = "--check" in sys.argv
    workspace = os.path.join(ROOT, "demo")
    if "--workspace" in sys.argv:
        workspace = os.path.abspath(sys.argv[sys.argv.index("--workspace") + 1])
    channels = load_channels()
    pdir = os.path.join(workspace, "pipelines")
    pipelines = [Pipeline(workspace, os.path.join(pdir, fn), channels)
                 for fn in sorted(os.listdir(pdir)) if fn.endswith(".json")]
    pdir2 = os.path.join(workspace, "plotters")
    plotters = [PlotterGen(workspace, os.path.join(pdir2, fn), channels, pipelines)
                for fn in sorted(os.listdir(pdir2)) if fn.endswith(".json")] if os.path.isdir(pdir2) else []
    files = {}
    for p in pipelines:
        files[os.path.join(LIBRARY, f"pipeline_{p.name}.h")] = p.header()
        files[os.path.join(LIBRARY, f"pipeline_{p.name}.cpp")] = p.executor()
        files[os.path.join(STRESS, f"stress_{p.name}.c")] = p.stress()
    # A region run per plotter (design/quality.perf.md, "Regions").
    for p in plotters:
        used = sorted({k["pipe"].name for k in p.kinds})
        externs = "".join(f"extern const stress_pipeline stress_binding_{u};\n" for u in used)
        refs = ", ".join(f"&stress_binding_{u}" for u in used)
        files[os.path.join(STRESS, f"stress_plotter_{p.name}.c")] = (
            banner(p.src, True) + f"/* The region run for {p.name}: regions of it grown, cleared, regrown, and drained, and\n"
            " * its scale plan (performance at several sizes). The bindings set its kinds' parameters. */\n"
            '#include "runtime.h"\n#include "stress.h"\n\n' + externs + "\n"
            "int main(int argc, char **argv) {\n"
            f"  const stress_pipeline *pipelines[] = {{{refs}}};\n"
            f"  return stress_region_main(argc, argv, FOUNDRY_PLOTTER_{p.C}, {c_string(p.name)}, pipelines, {len(used)});\n}}\n")
    fh, fc = fires_files(workspace)
    files[os.path.join(LIBRARY, "fires.h")] = fh
    files[os.path.join(LIBRARY, "fires.cpp")] = fc
    ph, pc = plotters_files(plotters)
    files[os.path.join(LIBRARY, "plotters.h")] = ph
    files[os.path.join(LIBRARY, "plotters.cpp")] = pc
    # Every pipeline by name: its type and default parameters (foundry_diag_spawn).
    reg = [banner("the workspace's pipelines/"),
           "// Every pipeline by name, for spawning by name (runtime_diag.h, foundry_diag_spawn).\n"
           "#include <cstring>\n\n#include \"pipelines_internal.h\"\n\n"]
    for p in pipelines:
        reg.append(f"const runtime::PipelineType *pipeline_type_{p.name}();\nvoid pipeline_defaults_{p.name}(void *out);\n")
    reg.append("\nnamespace pipelines {\n\nnamespace {\nconst Entry kEntries[] = {\n")
    for p in pipelines:
        reg.append(f"    {{{c_string(p.name)}, pipeline_type_{p.name}, pipeline_defaults_{p.name}}},\n")
    reg.append("};\n}  // namespace\n\nconst Entry *find(const char *name) {\n"
               "  for (const Entry &e : kEntries)\n    if (name && std::strcmp(e.name, name) == 0) return &e;\n"
               "  return nullptr;\n}\n\n}  // namespace pipelines\n")
    files[os.path.join(LIBRARY, "pipelines.cpp")] = "".join(reg)
    with open(os.path.join(LIBRARY, "foundry.h")) as f:
        core = f.read()
    with open(os.path.join(LIBRARY, "region.h")) as f:
        core += "\n" + f.read()
    with open(os.path.join(LIBRARY, "sky.h")) as f:
        core += "\n" + f.read()
    with open(os.path.join(LIBRARY, "fire.h")) as f:
        core += "\n" + f.read()
    with open(os.path.join(LIBRARY, "ground.h")) as f:
        core += "\n" + f.read()
    runtime_h = ["/* runtime.h: the game-facing API (design/api.md). Assembled by tools/gen_pipelines.py from\n"
                 " * the fragments in src/library/: foundry.h, region.h, sky.h, fire.h, ground.h, each pipeline by name, then the plotters. Do not edit. */\n"
                 "#pragma once\n\n", core]
    for p in pipelines:
        runtime_h.append("\n" + files[os.path.join(LIBRARY, f"pipeline_{p.name}.h")])
    runtime_h.append("\n" + ph)
    files[os.path.join(LIBRARY, "runtime.h")] = "".join(runtime_h)
    stale = []
    for path, text in files.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as f:
                    f.write(text)
    # Remove stress bindings whose pipeline is gone.
    if os.path.isdir(STRESS):
        for fn in os.listdir(STRESS):
            path = os.path.join(STRESS, fn)
            if path not in files:
                stale.append(os.path.relpath(path, ROOT))
                if not check:
                    os.remove(path)
    if check and stale:
        sys.exit("generated pipeline code is stale; run tools/gen_pipelines.py:\n  " + "\n  ".join(stale))
    if not check:
        print(f"generated {len(files)} files from {len(pipelines)} pipelines ({len(stale)} changed)")


if __name__ == "__main__":
    main()
